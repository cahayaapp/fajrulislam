const assert=require('node:assert/strict');
const F=require('../js/education-findings-v2.js');
const assignment={unit:'PUTRA',programDomain:'KEPONDOKAN',area:'PENDIDIKAN'};
const schedule=[{id:'kbm-putra',guruKode:'FAIQ',guruNama:'Faiq'}];
assert.equal(F.status('Baru'),'BARU');
assert.equal(F.status('baru'),'BARU');
assert.equal(F.status('BARU'),'BARU');
assert.equal(F.status('Menunggu Perbaikan'),'MENUNGGU_PERBAIKAN');
assert.equal(F.status('Selesai'),'SELESAI');
assert.equal(F.jakartaDate('2026-09-18T17:30:00.000Z'),'2026-09-19');
assert.equal(F.jakartaDate('2026-09-18'),'2026-09-18');
const current=F.normalizeEducationFinding({tanggal:'2026-09-19',area:'PENDIDIKAN',unit:'PUTRA',programDomain:'KEPONDOKAN',status:'Baru',temuan:'Tes'},'finding-1');
assert.equal(current.id,'finding-1');assert.equal(current.status,'BARU');assert.equal(F.inManagerScope(current,assignment,schedule),true);
assert.equal(F.inManagerScope({...current,unit:'PUTRI'},assignment,schedule),false);
assert.equal(F.inManagerScope({...current,programDomain:'PKBM'},assignment,schedule),false);
assert.equal(F.inManagerScope({...current,area:'PEMBINAAN_KARAKTER'},assignment,schedule),false);
const legacy=F.normalizeEducationFinding({date:'2026-09-19',guru:'Faiq',status:'Selesai',masalah:'Lama'},'legacy-1');
assert.equal(F.inManagerScope(legacy,assignment,schedule),true);
assert.equal(F.inManagerScope({...legacy,personil:'Tidak Dikenal'},assignment,schedule),false);
assert.equal(F.inDateRange(legacy,'2026-09-19','2026-09-19'),true);
console.log('education-findings-v2: ok');
